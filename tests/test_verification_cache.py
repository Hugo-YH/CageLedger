import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import verification_cache as cache


class VerificationEvidenceTests(unittest.TestCase):
    def test_only_complete_matching_scope_and_unchanged_log_can_be_reused(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            log = root / "run.log"
            job = [sys.executable, "scripts/run_python_tests.py", "tests.domain"]
            log.write_text("...\nRan 3 tests in 0.1s\n\nOK\n")
            cache.remember(root / "cache", "input-v1", job, log)
            self.assertIsNotNone(cache.lookup(root / "cache", "input-v1", job))
            self.assertIsNone(cache.lookup(root / "cache", "input-v2", job))
            self.assertIsNone(cache.lookup(root / "cache", "input-v1", job + ["tests.other"]))
            log.write_text("interrupted or altered evidence")
            self.assertIsNone(cache.lookup(root / "cache", "input-v1", job))

    def test_zero_or_skipped_tests_do_not_produce_reusable_success(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            job = [sys.executable, "scripts/run_python_tests.py", "tests.domain"]
            log = root / "run.log"
            log.write_text("Ran 0 tests in 0s\nOK\n")
            with self.assertRaisesRegex(RuntimeError, "零个"):
                cache.remember(root / "cache", "zero", job, log)
            log.write_text("Ran 4 tests in 0s\nOK (skipped=2)\n")
            cache.remember(root / "cache", "skipped", job, log)
            self.assertIsNone(cache.lookup(root / "cache", "skipped", job))

    def test_source_or_runtime_changes_invalidate_but_commit_identity_is_not_an_input(self):
        repo = Path("/source")
        job = ["node", "node_modules/vitest/vitest.mjs", "run", "src/one.test.ts"]
        with (
            patch.object(cache, "source_fingerprint", return_value="content-a") as source,
            patch.object(cache, "command", return_value='{"version":"v22","path":"/node"}'),
            patch.object(cache, "digest", return_value="installed-a") as digest,
        ):
            first = cache.inputs(repo, job, {})
            self.assertEqual(cache.inputs(repo, job, {}), first)
            source.return_value = "content-b"
            self.assertNotEqual(cache.inputs(repo, job, {}), first)
            source.return_value = "content-a"
            digest.return_value = "installed-b"
            self.assertNotEqual(cache.inputs(repo, job, {}), first)

    def test_import_cache_files_do_not_invalidate_installed_dependency_signature(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            (root / "library.py").write_text("version = 1\n")
            first = cache.metadata(root)
            (root / "__pycache__").mkdir()
            (root / "__pycache__/library.pyc").write_bytes(b"generated bytecode")
            self.assertEqual(cache.metadata(root), first)
            (root / "library.py").write_text("version = 2\n")
            self.assertNotEqual(cache.metadata(root), first)
